/**
 * Vercel / CI: set API_URL before `ng build` to override the Blitz API URL.
 * Example: API_URL=https://briskpeople.blitz.cloud/api
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const normalizedApiUrl = 'https://briskpeople.blitz.cloud/api';
const baseDomain = process.env.BASE_DOMAIN || 'briskpeople.com';

const contents = `// Auto-generated by scripts/write-production-environment.mjs — do not edit on Vercel builds
export const environment = {
  production: true,
  apiUrl: '${normalizedApiUrl}',
  baseDomain: '${baseDomain}',
  apiKey: '',
  appName: 'HRMS Frontend',
  auth: {
    tokenKey: 'token',
    refreshTokenKey: 'refresh_token',
    userKey: 'user'
  }
};
`;

const target = join(root, 'src', 'environments', 'environment.production.ts');
writeFileSync(target, contents, 'utf8');
console.log(`Wrote production environment apiUrl=${normalizedApiUrl}`);
