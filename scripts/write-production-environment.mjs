/**
 * Vercel / CI: set API_URL before `ng build` to override the Blitz API URL.
 * Example: API_URL=https://briskpeople.prod.page/api
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const DEFAULT_API_URL = 'https://briskpeople.prod.page/api';

/** Accepts "https://host", "https://host/" or "https://host/api"; anything else falls back to the default. */
function resolveApiUrl(raw) {
  if (!raw) return DEFAULT_API_URL;
  let url;
  try {
    url = new URL(raw);
  } catch {
    console.warn(`API_URL is not a valid URL; using ${DEFAULT_API_URL}`);
    return DEFAULT_API_URL;
  }
  if (!['http:', 'https:'].includes(url.protocol)) {
    console.warn(`API_URL must be http(s); using ${DEFAULT_API_URL}`);
    return DEFAULT_API_URL;
  }
  const path = url.pathname.replace(/\/+$/, '');
  if (path.endsWith('/api')) return `${url.origin}${path}`;
  // Any other path (e.g. "/index.html") is not the API: use the host's /api.
  console.warn(`API_URL path "${url.pathname}" does not end in /api; using ${url.origin}/api`);
  return `${url.origin}/api`;
}

const normalizedApiUrl = resolveApiUrl(process.env.API_URL?.trim());
const baseDomain = process.env.BASE_DOMAIN || 'briskpeople.com';

const contents = `// Auto-generated by scripts/write-production-environment.mjs — do not edit on Vercel builds
export const environment = {
  production: true,
  apiUrl: ${JSON.stringify(normalizedApiUrl)},
  baseDomain: ${JSON.stringify(baseDomain)},
  apiKey: '',
  appName: 'HRMS Frontend',
  auth: {
    tokenKey: 'token',
    refreshTokenKey: 'refresh_token',
    userKey: 'user'
  }
};
`;

const target = join(root, 'src', 'environments', 'environment.production.ts');
writeFileSync(target, contents, 'utf8');
console.log(`Wrote production environment apiUrl=${normalizedApiUrl}`);
