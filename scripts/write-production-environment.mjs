/**
 * Vercel / CI: set API_URL before `ng build` to point the SPA at the Railway API.
 * Example: API_URL=https://hrmsapplicationcodifiedlabs-production.up.railway.app/api
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

const defaultApiUrl = 'https://hrmsapplicationcodifiedlabs-production.up.railway.app/api';
const apiUrl = (process.env.API_URL || process.env.NG_APP_API_URL || defaultApiUrl).replace(/\/$/, '');
const normalizedApiUrl = apiUrl.endsWith('/api') ? apiUrl : `${apiUrl}/api`;

const contents = `// Auto-generated by scripts/write-production-environment.mjs — do not edit on Vercel builds
export const environment = {
  production: true,
  apiUrl: '${normalizedApiUrl}',
  apiKey: '',
  appName: 'HRMS Frontend',
  auth: {
    tokenKey: 'token',
    refreshTokenKey: 'refresh_token',
    userKey: 'user'
  }
};
`;

const target = join(root, 'src', 'environments', 'environment.production.ts');
writeFileSync(target, contents, 'utf8');
console.log(`Wrote production environment apiUrl=${normalizedApiUrl}`);
